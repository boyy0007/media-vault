/// <reference path="../pb_data/types.d.ts" />
// Trash, duplicate fingerprints and share links.
//
// media.trashedAt  set = the item is in Trash (hidden everywhere else); a cron in pb_hooks/library.pb.js
//                  deletes items for good 30 days after this date.
// media.hash       content fingerprint computed in the browser at upload (see fingerprint() in app.js),
//                  used to skip duplicate uploads. Older items get one lazily, only when a file of the
//                  same byte size is uploaded.
// shares           public links to an album or a set of items. `token` is generated by the server and
//                  is the only secret; the public endpoints live in pb_hooks/share.pb.js.

const OWNER = "owner = @request.auth.id";
const KEEP_OWNER = "(@request.body.owner:isset = false || @request.body.owner = @request.auth.id)";

migrate((app) => {
  const media = app.findCollectionByNameOrId("media");
  media.fields.add(new DateField({ name: "trashedAt" }));
  media.fields.add(new TextField({ name: "hash", max: 100 }));
  media.addIndex("idx_media_owner_hash", false, "owner, hash", "");
  media.addIndex("idx_media_owner_trashed", false, "owner, trashedAt", "");
  app.save(media);

  const users = app.findCollectionByNameOrId("users");
  const albums = app.findCollectionByNameOrId("albums");
  const shares = new Collection({
    type: "base",
    name: "shares",
    listRule: OWNER,
    viewRule: OWNER,
    // token/views are server-managed; album/items are checked against the owner in pb_hooks/share.pb.js
    createRule: "@request.auth.id != '' && @request.body.owner = @request.auth.id && @request.body.token:isset = false && @request.body.views:isset = false",
    updateRule: `${OWNER} && ${KEEP_OWNER} && @request.body.token:isset = false && @request.body.views:isset = false && @request.body.album:isset = false && @request.body.items:isset = false`,
    deleteRule: OWNER,
    fields: [
      { type: "relation", name: "owner", collectionId: users.id, maxSelect: 1, required: true, cascadeDelete: true },
      { type: "text", name: "token", required: true, min: 24, max: 24, autogeneratePattern: "[a-zA-Z0-9]{24}", hidden: false },
      { type: "text", name: "title", max: 200 },
      { type: "relation", name: "album", collectionId: albums.id, maxSelect: 1, cascadeDelete: true },
      { type: "relation", name: "items", collectionId: media.id, maxSelect: 5000, cascadeDelete: false },
      { type: "bool", name: "allowDownload" },
      { type: "date", name: "expires" },
      { type: "number", name: "views", min: 0, onlyInt: true },
      { type: "autodate", name: "created", onCreate: true, onUpdate: false },
      { type: "autodate", name: "updated", onCreate: true, onUpdate: true },
    ],
    indexes: [
      "CREATE UNIQUE INDEX idx_shares_token ON shares (token)",
      "CREATE INDEX idx_shares_owner ON shares (owner)",
    ],
  });
  app.save(shares);
}, (app) => {
  try { app.delete(app.findCollectionByNameOrId("shares")); } catch (_) {}
  const media = app.findCollectionByNameOrId("media");
  media.removeIndex("idx_media_owner_hash");
  media.removeIndex("idx_media_owner_trashed");
  media.fields.removeByName("trashedAt");
  media.fields.removeByName("hash");
  app.save(media);
});
